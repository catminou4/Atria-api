from __future__ import annotations

import argparse
import logging
import sys
import uuid
from pathlib import Path

from .challenge import AlibabaCloudChallengeDriver, FixtureChallengeDriver
from .config import AppConfig, load_config
from .dashboard import Dashboard
from .driver import AtriaPlaywrightDriver, FixtureRegistrationDriver
from .keystore import KeyStore
from .mailbox import CatchAllImapMailboxReader, FixtureMailboxReader
from .pacing import NoopPacer, SingleLanePacer
from .pipeline import Pipeline
from .redaction import configure_logging
from .state import StateStore


LOGGER = logging.getLogger(__name__)


def _default_config() -> Path:
    return Path(__file__).resolve().parent.parent / "config" / "atria.yaml"


def _components(config: AppConfig, fixture: bool, fixture_variant: str):
    state = StateStore(config.state_path)
    keystore = KeyStore(config.keystore_path)
    if fixture:
        mailbox = FixtureMailboxReader()
        pacer = NoopPacer()

        def make_driver():
            return FixtureRegistrationDriver()

        def make_challenge():
            return FixtureChallengeDriver(config.artifact_dir, fixture_variant)

    else:
        if config.mailbox.kind != "imap_catchall":
            raise ValueError(f"unsupported mailbox reader: {config.mailbox.kind}")
        mailbox = CatchAllImapMailboxReader(config.mailbox)
        pacer = SingleLanePacer(config.state_path, config.pacing)

        def make_driver():
            return AtriaPlaywrightDriver(
                config.registration_url,
                config.session_dir,
                config.artifact_dir,
                headed=config.headed,
            )

        def make_challenge():
            return AlibabaCloudChallengeDriver(
                config.artifact_dir, config.challenge_timeout_seconds
            )

    return state, keystore, mailbox, pacer, make_driver, make_challenge


def command_run(args: argparse.Namespace, config: AppConfig) -> int:
    state, keystore, mailbox, pacer, make_driver, make_challenge = _components(
        config, args.fixture, args.fixture_variant
    )
    dashboard = Dashboard(state, keystore, config.dashboard_port)
    if not args.no_dashboard:
        try:
            dashboard.start()
            LOGGER.info("dashboard=http://127.0.0.1:%d", config.dashboard_port)
        except OSError as exc:
            LOGGER.warning("dashboard unavailable: %s", exc)

    if args.resume:
        run_ids = [args.resume]
    else:
        pending = [row.run_id for row in state.incomplete_runs()]
        run_ids = pending[: args.count]
        run_ids.extend(uuid.uuid4().hex for _ in range(args.count - len(run_ids)))

    failures = 0
    try:
        for run_id in run_ids:
            try:
                pacer.acquire()
            except Exception as exc:
                LOGGER.error("pacing prevented run=%s: %s", run_id, exc)
                failures += 1
                continue
            pipeline = Pipeline(
                state=state,
                mailbox=mailbox,
                driver=make_driver(),
                challenge=make_challenge(),
                keystore=keystore,
                pending_dir=config.pending_dir,
                pacer=pacer,
                retry_bounds=(0, 0) if args.fixture else (2, 8),
            )
            result = pipeline.run(run_id=run_id, email=args.email)
            if result.status == "completed":
                LOGGER.info("run=%s completed key_id=%s", result.run_id, result.key_id)
            else:
                failures += 1
                LOGGER.error(
                    "run=%s failed class=%s reason=%s artifact=%s",
                    result.run_id,
                    result.failure_class,
                    result.error_code,
                    result.artifact or "none",
                )
    finally:
        dashboard.stop()
    return 1 if failures else 0


def command_dashboard(config: AppConfig) -> int:
    dashboard = Dashboard(StateStore(config.state_path), KeyStore(config.keystore_path), config.dashboard_port)
    LOGGER.info("dashboard=http://127.0.0.1:%d", config.dashboard_port)
    try:
        dashboard.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="atria-keys")
    parser.add_argument("--config", default=str(_default_config()))
    parser.add_argument("--verbose", action="store_true")
    commands = parser.add_subparsers(dest="command", required=True)

    run = commands.add_parser("run", help="run or resume local provisioning")
    run.add_argument("--count", type=int, default=1)
    run.add_argument("--resume", metavar="RUN_ID")
    run.add_argument("--email", help="fixed recipient (normally generated by mailbox reader)")
    run.add_argument("--fixture", action="store_true", help="offline deterministic fixture mode")
    run.add_argument(
        "--fixture-variant", default="supported", help=argparse.SUPPRESS
    )
    run.add_argument("--no-dashboard", action="store_true")

    commands.add_parser("dashboard", help="serve the read-only local dashboard")
    export = commands.add_parser("export", help="export stored keys")
    export.add_argument("--format", choices=("txt", "env"), required=True)
    export.add_argument("--output", required=True)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose)
    if getattr(args, "count", 1) < 1:
        parser.error("--count must be positive")
    config = load_config(args.config)
    if args.command == "run":
        return command_run(args, config)
    if args.command == "dashboard":
        return command_dashboard(config)
    if args.command == "export":
        target = KeyStore(config.keystore_path).export(args.output, args.format)
        LOGGER.info("exported keys to %s", target)
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())

